/**
 * MockPdfValidator.ts
 *
 * Compares a CLIENT TEMPLATE PDF (with {{variables}}) against a PREVIEW PDF
 * (with values filled in), validating that:
 *
 *   1. Every {{variable}} in the template was resolved (no blanks in the preview).
 *   2. Each supplied UI value appears in the preview PDF text.
 *   3. Each required static statement appears in the preview PDF text.
 *
 * ── THE TWO PDFs ─────────────────────────────────────────────────────────────
 *
 *   templatePdfPath   test-data/mock-pdfs/template/<FormNumber>.pdf
 *     → Client-supplied PDF. Contains {{Named Insured}}, {{Policy Number}} etc.
 *       as literal text. This is what the client hands over as their form template.
 *
 *   previewPdfPath    test-data/mock-pdfs/preview/<FormNumber>.pdf
 *     → Mock of what the in-app viewer renders. Same layout but {{variables}}
 *       replaced by real values. Generated by scripts/generate-mock-pdfs.ts.
 *       When the real viewer ships, this PDF comes from the new browser tab
 *       — the switch is in FormsPage (USE_MOCK_PDF env var).
 *
 * ── USAGE ────────────────────────────────────────────────────────────────────
 *
 *   const result = await MockPdfValidator.comparePdfs({
 *     templatePdfPath: 'test-data/mock-pdfs/template/BR-001.pdf',
 *     previewPdfPath:  'test-data/mock-pdfs/preview/BR-001.pdf',
 *     values: {
 *       'Named Insured':  'Acme Construction LLC',
 *       'Policy Number':  'BR-2025-001234',
 *       ...
 *     },
 *     requiredStatements: [
 *       'direct physical loss or damage to covered property',
 *     ],
 *   });
 *
 *   expect(result.passed, result.summary).toBe(true);
 *
 * ── DEPENDENCY ───────────────────────────────────────────────────────────────
 *
 *   pdf-parse is already installed via PdfValidator.
 */

import { MockPdfViewer, type TemplateValues } from './MockPdfViewer';

// ── Types ─────────────────────────────────────────────────────────────────────

export interface MockComparePdfsInput {
  /** Path to the client template PDF (contains {{variables}}) */
  templatePdfPath: string;
  /** Path to the preview PDF (variables replaced by real values) */
  previewPdfPath:  string;
  /** Variable name → live UI value */
  values:          TemplateValues;
  /** Static strings that must appear verbatim in the preview PDF */
  requiredStatements?: string[];
  /** Case-insensitive comparison (default: false) */
  caseInsensitive?: boolean;
}

export interface MockCheckResult {
  checkType:  'variable_resolved' | 'value_in_preview' | 'statement_in_preview' | 'no_unresolved_placeholders';
  label:      string;
  expected:   string;
  found:      boolean;
  detail?:    string;
}

export interface MockCompareResult {
  passed:              boolean;
  summary:             string;
  /** Text extracted from the template PDF */
  templateText:        string;
  /** Text extracted from the preview PDF */
  previewText:         string;
  /** Template text with {{variables}} substituted (expected preview content) */
  renderedText:        string;
  /** Variables from the template that had no supplied value */
  unresolvedVars:      string[];
  checks:              MockCheckResult[];
  failures:            MockCheckResult[];
}

// ── MockPdfValidator ──────────────────────────────────────────────────────────

export class MockPdfValidator {

  /**
   * Compares the two PDFs:
   *   1. Extracts text from the template PDF → finds all {{variables}}.
   *   2. Renders template text with supplied values → expected content.
   *   3. Extracts text from the preview PDF → actual content.
   *   4. Verifies each UI value and required statement appears in the preview PDF.
   */
  static async comparePdfs(input: MockComparePdfsInput): Promise<MockCompareResult> {
    const {
      templatePdfPath,
      previewPdfPath,
      values,
      requiredStatements = [],
      caseInsensitive = false,
    } = input;

    // ── 1. Extract text from both PDFs ────────────────────────────────────
    const [renderResult, previewText] = await Promise.all([
      MockPdfViewer.renderFromPdf(templatePdfPath, values),
      MockPdfViewer.extractText(previewPdfPath),
    ]);

    const { renderedText, templateText, unresolved } = renderResult;

    const normalize  = (s: string) => caseInsensitive ? s.toLowerCase() : s;
    const haystack   = normalize(previewText);
    const checks: MockCheckResult[] = [];

    // ── 2. Check: no unresolved placeholders in template ──────────────────
    if (unresolved.length === 0) {
      checks.push({
        checkType: 'no_unresolved_placeholders',
        label:     'All template variables have supplied values',
        expected:  '(no {{...}} variables without a value)',
        found:     true,
      });
    } else {
      for (const v of unresolved) {
        checks.push({
          checkType: 'variable_resolved',
          label:     `Variable has a value: {{${v}}}`,
          expected:  `A UI value for "${v}"`,
          found:     false,
          detail:    `No value supplied for {{${v}}} — it will appear as a blank in the preview PDF`,
        });
      }
    }

    // ── 3. Check: each UI value appears in the PREVIEW PDF ────────────────
    for (const [varName, value] of Object.entries(values)) {
      if (!value.trim()) continue;
      const needle = normalize(value.trim());
      const found  = haystack.includes(needle);
      checks.push({
        checkType: 'value_in_preview',
        label:     `"${varName}" value in preview PDF: "${value}"`,
        expected:  value,
        found,
        detail:    found
          ? undefined
          : `Value "${value}" (for variable "${varName}") not found in preview PDF text`,
      });
    }

    // ── 4. Check: required static statements in PREVIEW PDF ───────────────
    for (const stmt of requiredStatements) {
      const needle = normalize(stmt.trim());
      const found  = haystack.includes(needle);
      checks.push({
        checkType: 'statement_in_preview',
        label:     `Statement in preview PDF: "${stmt.substring(0, 60)}${stmt.length > 60 ? '…' : ''}"`,
        expected:  stmt,
        found,
        detail:    found
          ? undefined
          : `Required statement not found in preview PDF: "${stmt}"`,
      });
    }

    // ── 5. Build result ───────────────────────────────────────────────────
    const failures = checks.filter(c => !c.found);
    const passed   = failures.length === 0;

    const summary = passed
      ? `✅ Mock PDF comparison passed — ${checks.length} check(s) OK`
      : `❌ Mock PDF comparison FAILED — ${failures.length} of ${checks.length} check(s) failed`;

    return {
      passed,
      summary,
      templateText,
      previewText,
      renderedText,
      unresolvedVars: unresolved,
      checks,
      failures,
    };
  }

  /**
   * Throws if the comparison fails. Handy inside a test without checking .passed.
   */
  static async comparePdfsOrThrow(input: MockComparePdfsInput): Promise<MockCompareResult> {
    const result = await this.comparePdfs(input);
    if (!result.passed) {
      const lines = [
        result.summary,
        '',
        ...result.failures.map(f =>
          `  ✗ ${f.label}${f.detail ? '\n      ' + f.detail : ''}`,
        ),
      ];
      throw new Error(lines.join('\n'));
    }
    return result;
  }

  /**
   * Prints a human-readable diff-style report to stdout.
   */
  static printReport(result: MockCompareResult): void {
    console.log('\n' + '─'.repeat(72));
    console.log(result.summary);
    console.log('─'.repeat(72));

    if (result.unresolvedVars.length > 0) {
      console.log('\nUnresolved template variables (no UI value supplied):');
      result.unresolvedVars.forEach(v => console.log(`  ⚠  {{${v}}}`));
    }

    if (result.failures.length > 0) {
      console.log('\nFailed checks:');
      result.failures.forEach(f => {
        console.log(`  ✗  ${f.label}`);
        if (f.detail) console.log(`       ${f.detail}`);
      });
    }

    const passed = result.checks.filter(c => c.found);
    console.log(`\nPassed checks (${passed.length}/${result.checks.length}):`);
    passed.forEach(c => console.log(`  ✓  ${c.label}`));

    console.log('\nPreview PDF text preview (first 15 lines):');
    result.previewText.split('\n').slice(0, 15).forEach(l => console.log('  │ ' + l));
    console.log('─'.repeat(72) + '\n');
  }

  /**
   * Returns all {{Variable}} names declared in a template PDF.
   */
  static async requiredVariables(templatePdfPath: string): Promise<string[]> {
    return MockPdfViewer.extractVariablesFromPdf(templatePdfPath);
  }
}
