/**
 * generate-mock-pdfs.ts
 *
 * Generates two PDF files per form found in the Excel manifest:
 *
 *   test-data/mock-pdfs/template/<UnqorkFormNumber>.pdf
 *     → Client template PDF — text contains {{Variable}} placeholders.
 *
 *   test-data/mock-pdfs/preview/<UnqorkFormNumber>.pdf
 *     → Preview PDF — same layout but placeholders replaced with sample values.
 *
 * ── HOW IT WORKS ─────────────────────────────────────────────────────────────
 *
 *   This script reads EVERY form from form-manifest.xlsx and auto-generates
 *   PDFs directly from the form's metadata (form name + field labels).
 *   You NEVER need to edit this script when adding new forms.
 *
 *   To add a new form:
 *     1. Add rows to test-data/form-manifest.xlsx (one row per field).
 *     2. Run:  npx tsx scripts/generate-mock-pdfs.ts
 *     3. Done — template + preview PDFs are created automatically.
 *
 * ── SAMPLE VALUES ─────────────────────────────────────────────────────────────
 *
 *   Preview PDFs are generated by substituting {{Variable}} with sample values.
 *   Override specific values in test-data/mock-pdf-values.ts under the
 *   SAMPLE_VALUES export.  Any variable NOT found there gets a sensible
 *   auto-generated placeholder (e.g. "Named Insured" → "Sample Named Insured").
 *
 * ── RUN ───────────────────────────────────────────────────────────────────────
 *
 *   npx tsx scripts/generate-mock-pdfs.ts
 *   npx tsx scripts/generate-mock-pdfs.ts --dry-run   ← list forms without writing
 *
 * ── DEPENDENCIES ──────────────────────────────────────────────────────────────
 *
 *   npm install --save-dev pdfkit @types/pdfkit exceljs
 */

