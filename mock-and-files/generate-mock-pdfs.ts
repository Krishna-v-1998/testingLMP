// ── PDF builder ───────────────────────────────────────────────────────────────

function substitute(text: string, values: Record<string, string>): string {
  return text.replace(/\{\{\s*(.+?)\s*\}\}/g, (_, varName: string) =>
    resolveValue(varName.trim(), values),
  );
}

async function buildPdf(
  outputPath: string,
  form:       FormForPdf,
  values:     Record<string, string> | null,  // null = keep {{variables}} as template
): Promise<void> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: 'LETTER' });
    const out = fs.createWriteStream(outputPath);
    out.on('error', reject);
    doc.on('error', reject);
    doc.pipe(out);

    const render = (t: string) => (values ? substitute(t, values) : t);

    // ── Header ──────────────────────────────────────────────────────────────
    doc.fontSize(13).font('Helvetica-Bold').text(form.formName.toUpperCase(), { align: 'center' });
    doc.fontSize(9).font('Helvetica').text(`Form ${form.lotusNotesFormId}`, { align: 'center' });
    doc.moveDown(0.4);
    doc.moveTo(50, doc.y).lineTo(560, doc.y).stroke();
    doc.moveDown(0.6);

    // ── Declarations / field table ───────────────────────────────────────────
    if (form.fields.length > 0) {
      doc.fontSize(10).font('Helvetica-Bold').text('DECLARATIONS');
      doc.moveTo(50, doc.y).lineTo(560, doc.y).strokeColor('#cccccc').stroke().strokeColor('black');
      doc.moveDown(0.3);

      for (const field of form.fields) {
        const label    = `${field.label}:`.padEnd(28);
        const valueStr = render(`{{${field.varName}}}`);
        doc.fontSize(9).font('Helvetica').text(`${label}${valueStr}`, { lineGap: 2 });
      }
      doc.moveDown(0.8);
    }

    // ── Coverage agreement ───────────────────────────────────────────────────
    doc.fontSize(10).font('Helvetica-Bold').text('COVERAGE AGREEMENT');
    doc.moveTo(50, doc.y).lineTo(560, doc.y).strokeColor('#cccccc').stroke().strokeColor('black');
    doc.moveDown(0.3);

    const namedInsured = render('{{Named Insured}}');
    const policyNumber = render('{{Policy Number}}');

    doc.fontSize(9).font('Helvetica').text(
      `In consideration of the premium paid by ${namedInsured}, and subject to all terms and ` +
      `conditions of this policy, the insurer agrees to provide coverage as described herein.`,
      { lineGap: 2 },
    );
    doc.moveDown(0.4);
    doc.text(
      `This policy is issued under form number ${form.lotusNotesFormId} and forms part of ` +
      `policy number ${policyNumber}.`,
      { lineGap: 2 },
    );
    doc.moveDown(0.8);

    // ── Footer ───────────────────────────────────────────────────────────────
    doc.fontSize(8).font('Helvetica').fillColor('#666666').text(
      'ALL OTHER TERMS AND CONDITIONS OF THIS POLICY REMAIN UNCHANGED.',
      { align: 'center' },
    );

    doc.end();
    out.on('finish', resolve);
  });
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main(): Promise<void> {
  console.log('═'.repeat(60));
  console.log('  generate-mock-pdfs.ts');
  console.log('═'.repeat(60));

  // 1. Load forms from manifest (or fall back to built-in samples)
  let forms = await readFormsFromManifest();
  if (forms.length === 0) {
    console.log('Using built-in sample forms (3 forms).');
    forms = FALLBACK_FORMS;
  } else {
    console.log(`Loaded ${forms.length} unique form(s) from manifest.\n`);
  }

  if (DRY_RUN) {
    console.log('\n── DRY RUN — no files written ──────────────────────────────');
    for (const f of forms) {
      console.log(`  ${f.unqorkFormNumber}  |  ${f.formName}  |  ${f.fields.length} field(s)`);
    }
    return;
  }

  // 2. Load sample values
  const customValues = loadSampleValues();
  console.log(`Custom sample values loaded: ${Object.keys(customValues).length} entries`);

  // 3. Create output directories
  [TEMPLATE_DIR, PREVIEW_DIR].forEach(d => fs.mkdirSync(d, { recursive: true }));

  // 4. Build sample value map for each form (auto-fills unknown variables)
  for (const form of forms) {
    const sampleValues: Record<string, string> = {};
    for (const field of form.fields) {
      sampleValues[field.varName] = resolveValue(field.varName, customValues);
    }
    // Always include common variables even if not in fields list
    for (const common of ['Named Insured', 'Policy Number', 'Effective Date', 'Expiration Date']) {
      if (!sampleValues[common]) {
        sampleValues[common] = resolveValue(common, customValues);
      }
    }

    const templatePath = path.join(TEMPLATE_DIR, `${form.unqorkFormNumber}.pdf`);
    const previewPath  = path.join(PREVIEW_DIR,  `${form.unqorkFormNumber}.pdf`);

    await buildPdf(templatePath, form, null);         // keep {{variables}}
    await buildPdf(previewPath,  form, sampleValues); // substitute values

    console.log(`  ✓  ${form.unqorkFormNumber}  — ${form.formName}`);
    console.log(`       template: ${path.relative(process.cwd(), templatePath)}`);
    console.log(`       preview:  ${path.relative(process.cwd(), previewPath)}`);
    if (form.fields.length > 0) {
      console.log(`       variables: ${form.fields.map(f => `{{${f.varName}}}`).join(', ')}`);
    }
    console.log('');
  }

  console.log('─'.repeat(60));
  console.log(`Done. ${forms.length * 2} PDF file(s) written to test-data/mock-pdfs/`);
  console.log('─'.repeat(60));
}

main().catch(err => { console.error(err); process.exit(1); });
