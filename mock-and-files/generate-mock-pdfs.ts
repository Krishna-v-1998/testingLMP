const DRY_RUN = process.argv.includes('--dry-run');

// ── Types ─────────────────────────────────────────────────────────────────────

interface FormForPdf {
  unqorkFormNumber: string;
  formName:         string;
  lotusNotesFormId: string;
  fields:           Array<{ label: string; varName: string }>;
}

// ── Sample value resolution ───────────────────────────────────────────────────

/**
 * Load custom sample values from test-data/mock-pdf-values.ts if it exists.
 * Falls back to an empty map — auto-generation handles the rest.
 */
function loadSampleValues(): Record<string, string> {
  if (!fs.existsSync(SAMPLE_VALUES_PATH)) return {};
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const mod = require(SAMPLE_VALUES_PATH);
    // Support both  export default {...}  and  export const SAMPLE_VALUES = {...}
    return mod.SAMPLE_VALUES ?? mod.BR_SAMPLE_VALUES ?? mod.default ?? {};
  } catch {
    return {};
  }
}

/**
 * Generates a sensible sample value for a variable name when not found in the
 * custom sample values file.  No code changes needed for new variables.
 *
 * Rules (applied in order, case-insensitive):
 *   date / expir                → "01/01/2025"
 *   number / no / num / id      → "BR-2024-001"
 *   amount / value / premium / cost / price / deductible → "$1,000,000"
 *   percentage / rate / pct     → "10"
 *   address                     → "123 Main Street"
 *   city                        → "Los Angeles"
 *   state                       → "CA"
 *   zip                         → "90001"
 *   coverage / elected          → "Included"
 *   sprinkler                   → "Yes"
 *   everything else             → "Sample <Variable Name>"
 */
function autoSampleValue(varName: string): string {
  const n = varName.toLowerCase();
  if (/date|expir/.test(n))                                  return '01/01/2025';
  if (/number|no\b|num|id/.test(n))                          return 'BR-2024-001';
  if (/amount|value|premium|cost|price|deductible/.test(n))  return '$1,000,000';
  if (/percentage|rate|pct/.test(n))                         return '10';
  if (/address/.test(n))                                      return '123 Main Street';
  if (/city/.test(n))                                         return 'Los Angeles';
  if (/\bstate\b/.test(n))                                    return 'CA';
  if (/zip/.test(n))                                          return '90001';
  if (/coverage|elected/.test(n))                             return 'Included';
  if (/sprinkler/.test(n))                                    return 'Yes';
  return `Sample ${varName}`;
}

function resolveValue(varName: string, customValues: Record<string, string>): string {
  const key = varName.toLowerCase().trim();
  const hit  = Object.entries(customValues).find(([k]) => k.toLowerCase().trim() === key);
  return hit ? hit[1] : autoSampleValue(varName);
}

// ── Manifest reader ───────────────────────────────────────────────────────────

const SHEET_NAME = 'Forms';

/** Column header → property (lower-cased, spaces stripped) */
const COL_MAP: Record<string, string> = {
  unqorkformnumber: 'unqorkFormNumber',
  formname:         'formName',
  lotusnoteformid:  'lotusNotesFormId',
  lotusnoteformids: 'lotusNotesFormId',
  lotusnotesformid: 'lotusNotesFormId',
  fields:           'fieldLabel',
};

async function readFormsFromManifest(): Promise<FormForPdf[]> {
  if (!fs.existsSync(MANIFEST_PATH)) {
    console.warn(`\n⚠  Manifest not found at ${MANIFEST_PATH}`);
    console.warn('   Using built-in sample forms instead.\n');
    return [];
  }

  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(MANIFEST_PATH);

  const sheet = workbook.getWorksheet(SHEET_NAME) ?? workbook.worksheets[0];
  if (!sheet) return [];

  // Build column index from header row
  const colIndex: Record<string, number> = {};
  sheet.getRow(1).eachCell((cell, col) => {
    const key = String(cell.value ?? '').replace(/\s+/g, '').toLowerCase();
    const prop = COL_MAP[key];
    if (prop) colIndex[prop] = col;
  });

  const getCellValue = (row: ExcelJS.Row, prop: string): string => {
    const idx = colIndex[prop];
    if (!idx) return '';
    const v = row.getCell(idx).value;
    if (v === null || v === undefined) return '';
    if (typeof v === 'object') {
      if ('richText' in v) return (v as ExcelJS.CellRichTextValue).richText.map(r => r.text).join('').trim();
      if ('result'  in v) return String((v as ExcelJS.CellFormulaValue).result ?? '').trim();
      if ('text'    in v) return String((v as ExcelJS.CellHyperlinkValue).text  ?? '').trim();
    }
    return String(v).trim();
  };

  // Group rows by UnqorkFormNumber
  const formMap = new Map<string, FormForPdf>();

  sheet.eachRow((row, rowNum) => {
    if (rowNum === 1) return;

    const unqorkFormNumber = getCellValue(row, 'unqorkFormNumber');
    const formName         = getCellValue(row, 'formName');
    const lotusNotesFormId = getCellValue(row, 'lotusNotesFormId');
    const fieldLabel       = getCellValue(row, 'fieldLabel');

    if (!unqorkFormNumber) return;

    if (!formMap.has(unqorkFormNumber)) {
      formMap.set(unqorkFormNumber, {
        unqorkFormNumber,
        formName:         formName || unqorkFormNumber,
        lotusNotesFormId: lotusNotesFormId || unqorkFormNumber,
        fields:           [],
      });
    }

    // Derive variable name from field label (strip trailing punctuation)
    if (fieldLabel) {
      const varName = fieldLabel.replace(/[:\-–]+$/, '').trim();
      formMap.get(unqorkFormNumber)!.fields.push({ label: fieldLabel, varName });
    }
  });

  return Array.from(formMap.values());
}

