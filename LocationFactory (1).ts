import { LocationData } from '../../types/location.types';

/**
 * LocationFactory
 *
 * Pre-built LocationData objects for use in tests.
 *
 * ── HOW TO USE ─────────────────────────────────────────────────────────────
 *
 *   const data = LocationFactory.usaMinimal('001');
 *   await locationPage.addLocation(data);
 *
 * ── CUSTOMISE ──────────────────────────────────────────────────────────────
 *
 *   Each factory takes a required locationNo so tests control the ID:
 *
 *   const custom = { ...LocationFactory.usaMinimal('010'), city: 'Houston' };
 *   await locationPage.addLocation(custom);
 *
 * ── LOCATION NO. RULES ─────────────────────────────────────────────────────
 *
 *   - User manually types it (NOT auto-generated by the app)
 *   - Valid range: 001 – 999
 *   - Must be numeric; alphabets cause "Location No. should be between 001 and 999"
 *   - Use 3-digit zero-padded strings: '001', '042', '999'
 *   - Each test that adds a location should use a unique locationNo
 *     to avoid conflicts within the same submission.
 */
export class LocationFactory {

  /**
   * Minimal valid US location — only required fields.
   * Use for smoke tests and validation tests where values are not needed.
   *
   * @param locationNo - manually-assigned location number e.g. '001'
   */
  static usaMinimal(locationNo: string = '001'): LocationData {
    return {
      locationNo,
      country:       'USA',
      address:       '100 Main Street',
      city:          'New York',
      stateProvince: 'NY - New York',
      zipPostalCode: '10001',
      sprinklered:   'Yes',
    };
  }

  /**
   * Complete US location with all key fields for auto-calculation testing.
   *
   * Expected auto-calculations:
   *   Property Damage Total = 90 + 90 + 90 + 90 + 90 + 90 = 540
   *   BI/EE Total           = 90 + 0 = 90
   *   Location Total        = 540 + 90 = 630
   *
   * @param locationNo - manually-assigned location number e.g. '001'
   */
  static usaFull(locationNo: string = '001'): LocationData {
    return {
      locationNo,
      country:                 'USA',
      address:                 '5 Independence Way',
      address2:                'Suite 205',
      city:                    'New York',
      stateProvince:           'NY - New York',
      zipPostalCode:           '10001',
      sprinklered:             'Yes',
      buildingNo:              '1',
      occupancyCode:           'ADCl-0112 Oil & Natural Gas Exploration - Onshore',
      constructionDescription: 'Steel Frame',
      cotalityOccupancy:       'Site-Free Shell Barn',
      yearBuilt:               '1999',
      numberOfStories:         '5',
      areaSqFt:                '1800',
      buildingValue:           '90',
      contentsValue:           '90',
      stocksValue:             '90',
      machineryValue:          '90',
      edp:                     '90',
      otherDescription:        'Testing',
      otherDollar:             '90',
      businessInterruption:    '90',
    };
  }

  /**
   * Canadian location — uses Canadian province and postal code format.
   *
   * @param locationNo - manually-assigned location number e.g. '002'
   */
  static canada(locationNo: string = '002'): LocationData {
    return {
      locationNo,
      country:       'Canada',
      address:       '200 Bay Street',
      city:          'Toronto',
      stateProvince: 'ON - Ontario',
      zipPostalCode: 'M5J 2J1',
      sprinklered:   'No',
    };
  }

  /**
   * US location with high property values.
   *
   * Expected auto-calculations:
   *   Property Damage Total = 1,000,000 + 500,000 + 250,000 = 1,750,000
   *   BI/EE Total           = 200,000 + 50,000 = 250,000
   *   Location Total        = 1,750,000 + 250,000 = 2,000,000
   *
   * @param locationNo - manually-assigned location number e.g. '003'
   */
  static usaHighValue(locationNo: string = '003'): LocationData {
    return {
      locationNo,
      country:              'USA',
      address:              '300 Corporate Drive',
      city:                 'Houston',
      stateProvince:        'TX - Texas',
      zipPostalCode:        '77001',
      sprinklered:          'Yes',
      numberOfStories:      '10',
      areaSqFt:             '50000',
      buildingValue:        '1000000',
      contentsValue:        '500000',
      stocksValue:          '250000',
      businessInterruption: '200000',
      extraExpense:         '50000',
    };
  }

  /**
   * US location with no value fields.
   * Auto-calculated fields should show $0 or be empty.
   *
   * @param locationNo - manually-assigned location number e.g. '004'
   */
  static usaNoValues(locationNo: string = '004'): LocationData {
    return {
      locationNo,
      country:         'USA',
      address:         '400 Market Street',
      city:            'San Francisco',
      stateProvince:   'CA - California',
      zipPostalCode:   '94102',
      sprinklered:     'No',
      numberOfStories: '3',
      areaSqFt:        '5000',
      yearBuilt:       '2010',
    };
  }

  /**
   * Returns a sequence of unique minimal US locations with sequential location numbers.
   * Useful for bulk/upload tests that need multiple locations.
   *
   * @param count - How many locations to generate (max 9 to stay in 00x range)
   * @param startNo - Starting location number (default 1)
   */
  static sequence(count: number, startNo: number = 1): LocationData[] {
    return Array.from({ length: count }, (_, i) => {
      const no = String(startNo + i).padStart(3, '0');
      return {
        locationNo:    no,
        country:       'USA',
        address:       `${100 + i} Test Street`,
        city:          'New York',
        stateProvince: 'NY - New York',
        zipPostalCode: '10001',
        sprinklered:   'Yes' as const,
      };
    });
  }
}
